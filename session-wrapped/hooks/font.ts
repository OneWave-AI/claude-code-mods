/** Whether pixel (x, y) of `ch` is lit; unknown characters draw blank. */
export const lit = (ch: string, x: number, y: number) => {
  const rows = ROWS[ch] ?? ROWS[ch.toUpperCase()] ?? ROWS[' ']!
  return rows.split(' ')[y]?.[x] === '1'
}

/** The characters the font can draw: anything else becomes a space. */
export const printable = (text: string) =>
  [...text].map(ch => (ch === 'x' ? 'x' : ROWS[ch.toUpperCase()] ? ch.toUpperCase() : ' ')).join('')
